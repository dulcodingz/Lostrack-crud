    private void tblBarangMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblBarangMouseClicked
        // TODO add your handling code here:                                      
    int row = tblBarang.getSelectedRow();

    // Ambil ID
    id = Integer.parseInt(tblBarang.getValueAt(row, 0).toString());

    // Ambil data dari tabel
    String jenisDB = tblBarang.getValueAt(row, 1).toString();
    String nama = tblBarang.getValueAt(row, 2).toString();
    String lokasi = tblBarang.getValueAt(row, 3).toString();
     java.util.Date tanggal = (java.util.Date) tblBarang.getValueAt(row, 4);

    // Set field text
    txtNamaBarang.setText(nama);
    txtLokasi.setText(lokasi);
    dcTanggalDitemukan.setDate(tanggal);

    // Mapping jenis barang ke ComboBox
    boolean ditemukan = false;
    for (int i = 0; i < cmbJenisBarang.getItemCount(); i++) {
        if (cmbJenisBarang.getItemAt(i).equals(jenisDB)) {
            cmbJenisBarang.setSelectedIndex(i);
            ditemukan = true;
            break;
        }
    }

    // Jika tidak ada di ComboBox → Lainnya
    if (!ditemukan) {
        cmbJenisBarang.setSelectedItem("Lainnya");
        txtJenisLainnya.setEnabled(true);
        txtJenisLainnya.setText(jenisDB);
    } else {
        txtJenisLainnya.setText("");
        txtJenisLainnya.setEnabled(false);
    }

    // Aktifkan tombol
    btnUpdate.setEnabled(true);
    btnHapus.setEnabled(true);

    }//GEN-LAST:event_tblBarangMouseClicked


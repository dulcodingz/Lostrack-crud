    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        // TODO add your handling code here:
        String nama = txtNamaBarang.getText().trim();
        String lokasi = txtLokasi.getText().trim();
        String jenis;
        
        
        if (cmbJenisBarang.getSelectedIndex() == 0) {
            JOptionPane.showMessageDialog(this,
                "Silakan pilih jenis barang!",
                "Validasi",
                JOptionPane.WARNING_MESSAGE);
            cmbJenisBarang.requestFocus();
            return;
        }

    // Jika pilih "Lainnya"
    if (cmbJenisBarang.getSelectedItem().equals("Lainnya")) {
        jenis = txtJenisLainnya.getText().trim();
        if (jenis.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Isi jenis barang lainnya!",
                    "Validasi",
                    JOptionPane.WARNING_MESSAGE);
            txtJenisLainnya.requestFocus();
            return;
        }
    } else {
        jenis = cmbJenisBarang.getSelectedItem().toString();
    }

    // Validasi field lain
    if (nama.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Nama barang tidak boleh kosong!",
                "Validasi",
                JOptionPane.WARNING_MESSAGE);
        txtNamaBarang.requestFocus();
        return;
    }

    if (lokasi.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Lokasi ditemukan tidak boleh kosong!",
                "Validasi",
                JOptionPane.WARNING_MESSAGE);
        txtLokasi.requestFocus();
        return;
    }
    
    if (dcTanggalDitemukan.getDate() == null) {
        JOptionPane.showMessageDialog(this,
                "Tanggal ditemukan belum dipilih!",
                "Validasi",
                JOptionPane.WARNING_MESSAGE);
        dcTanggalDitemukan.requestFocus();
        return;
    }

// PROSES SIMPAN KE DATABASE
try {
    Connection conn = Koneksi.getKoneksi();
        String sql = "INSERT INTO temuan " +
                     "(jenis_barang, nama_barang, lokasi_ditemukan, tanggal_ditemukan) " +
                     "VALUES (?, ?, ?, ?)";
        PreparedStatement pst = conn.prepareStatement(sql);

        pst.setString(1, jenis);
        pst.setString(2, nama);
        pst.setString(3, lokasi);
        pst.setDate(4, new java.sql.Date(dcTanggalDitemukan.getDate().getTime()));

        pst.executeUpdate();

        JOptionPane.showMessageDialog(this,
                "Data berhasil disimpan!",
                "Sukses",
                JOptionPane.INFORMATION_MESSAGE);

        loadData();
        resetForm();

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Gagal menyimpan data: " + e.getMessage(),
                "Error",
                JOptionPane.ERROR_MESSAGE);
    }

    }//GEN-LAST:event_btnSimpanActionPerformed


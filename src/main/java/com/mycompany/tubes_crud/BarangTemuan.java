private void loadData() {
    DefaultTableModel model = new DefaultTableModel();

    // Header kolom tabel
    model.addColumn("ID");
    model.addColumn("Jenis Barang");
    model.addColumn("Nama Barang");
    model.addColumn("Lokasi Ditemukan");
    model.addColumn("Tanggal");

    try {
        Connection conn = Koneksi.getKoneksi();
        String sql = "SELECT id, jenis_barang, nama_barang, lokasi_ditemukan, tanggal_ditemukan " +
                     "FROM temuan ORDER BY tanggal_ditemukan DESC";
        PreparedStatement pst = conn.prepareStatement(sql);
        ResultSet rs = pst.executeQuery();

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getInt("id"),
                rs.getString("jenis_barang"),
                rs.getString("nama_barang"),
                rs.getString("lokasi_ditemukan"),
                rs.getDate("tanggal_ditemukan")
            });
        }

        tblBarang.setModel(model);

        

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Gagal memuat data: " + e.getMessage(),
                "Error",
                JOptionPane.ERROR_MESSAGE);
    }
}


